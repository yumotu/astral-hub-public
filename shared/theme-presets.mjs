export function themePreset(value) {
  return themePresets.find((p) => p.id === value) || themePresets[0];
}
export function themeColors(palette, appearance) {
  return themePreset(palette)[appearance === 'dark' ? 'dark' : 'light'];
}
export function appearanceMode(value, fallback = 'dark') {
  return ['light', 'dark', 'system'].includes(value) ? value : fallback;
}
export function resolvedAppearance(mode, systemDark) {
  return mode === 'system' ? (systemDark ? 'dark' : 'light') : mode === 'light' ? 'light' : 'dark';
}
